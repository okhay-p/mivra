import { type CourseIcon as CourseIconName, CourseIcon as CourseIconSchema } from "@mivra/protocol";
import {
  Atom,
  BookOpen,
  Brain,
  Briefcase,
  Calculator,
  Camera,
  ChartLine,
  Code,
  Cpu,
  Database,
  Dna,
  Dumbbell,
  FlaskConical,
  Globe,
  GraduationCap,
  HeartPulse,
  Landmark,
  Languages,
  Leaf,
  type LucideIcon,
  type LucideProps,
  Music,
  Network,
  Palette,
  PenTool,
  Scale,
  Shield,
  Sigma,
  Stethoscope,
  Telescope,
  Terminal,
  Users,
  Wrench,
} from "lucide-react";

const icons: Record<CourseIconName, LucideIcon> = {
  sigma: Sigma,
  calculator: Calculator,
  code: Code,
  terminal: Terminal,
  cpu: Cpu,
  database: Database,
  network: Network,
  shield: Shield,
  "flask-conical": FlaskConical,
  atom: Atom,
  dna: Dna,
  leaf: Leaf,
  telescope: Telescope,
  globe: Globe,
  landmark: Landmark,
  "book-open": BookOpen,
  "pen-tool": PenTool,
  languages: Languages,
  music: Music,
  palette: Palette,
  camera: Camera,
  brain: Brain,
  users: Users,
  "chart-line": ChartLine,
  briefcase: Briefcase,
  scale: Scale,
  stethoscope: Stethoscope,
  "heart-pulse": HeartPulse,
  wrench: Wrench,
  dumbbell: Dumbbell,
};

/** A course's subject icon (#58); a graduation cap before the tutor picks one, or for a name this client doesn't know. */
export function CourseIcon({ icon, ...props }: { icon: string | null | undefined } & LucideProps) {
  const parsed = CourseIconSchema.safeParse(icon);
  const Icon = parsed.success ? icons[parsed.data] : GraduationCap;
  return <Icon data-icon={parsed.success ? parsed.data : "graduation-cap"} {...props} />;
}
